CREATE TABLE volunteer_opportunity (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT                      NOT NULL REFERENCES organization (id),
    title           VARCHAR(255)                NOT NULL,
    description     VARCHAR(2000),
    location        VARCHAR(255),
    remote          BOOLEAN                     NOT NULL DEFAULT FALSE,
    starts_at       TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    ends_at         TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    slots           INTEGER                     NOT NULL CHECK (slots >= 1),
    filled_slots    INTEGER                     NOT NULL DEFAULT 0,
    status          VARCHAR(255)                NOT NULL,
    created_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT now(),
    version         BIGINT                      NOT NULL DEFAULT 0,
    CONSTRAINT chk_opportunity_period CHECK (ends_at > starts_at),
    CONSTRAINT chk_opportunity_filled_slots CHECK (filled_slots >= 0 AND filled_slots <= slots)
);

CREATE TABLE volunteer_application (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    opportunity_id  BIGINT                      NOT NULL REFERENCES volunteer_opportunity (id),
    volunteer_name  VARCHAR(255)                NOT NULL,
    volunteer_email VARCHAR(255)                NOT NULL,
    volunteer_phone VARCHAR(255),
    motivation      VARCHAR(2000),
    status          VARCHAR(255)                NOT NULL,
    created_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT uq_application_opportunity_email UNIQUE (opportunity_id, volunteer_email)
);

CREATE INDEX idx_opportunity_organization_id ON volunteer_opportunity (organization_id);
CREATE INDEX idx_opportunity_status_starts_at ON volunteer_opportunity (status, starts_at);
CREATE INDEX idx_application_opportunity_status ON volunteer_application (opportunity_id, status);
